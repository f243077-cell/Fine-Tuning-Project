"""Answer quality of the reference RAG on the golden set, guard off or on (Phase 7). Deterministic, no judge model.

    python evals/run_quality.py --guard off && python evals/run_quality.py --guard on

An answer is correct when every expected keyword appears in normalize_text(answer) and at least one source is
cited. demo-rag must run with ALLOW_GUARD_TOGGLE=true. Writes evals/reports/quality/quality_guard_<on|off>.json
and evals/reports/quality/QUALITY.md (with per-question differences when both runs exist).
"""

import argparse
import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

import httpx  # noqa: E402
import yaml  # noqa: E402

from training.normalize import normalize_text  # noqa: E402

GOLDEN = REPO / "evals" / "golden_set.yaml"
OUT = REPO / "evals" / "reports" / "quality"


def judge(answer: str, sources: list, keywords: list[str]) -> dict:
    """keyword_ok, cited, correct for one answer."""
    norm = normalize_text(answer)
    kw_ok = all(normalize_text(k) in norm for k in keywords)
    cited = len(sources) > 0
    return {"keyword_ok": kw_ok, "cited": cited, "correct": kw_ok and cited}


def rates(records: list[dict]) -> dict:
    """Correctness and citation rates overall and by surface."""
    def r(rs: list[dict]) -> dict:
        n = len(rs)
        return {"n": n, "correct": sum(x["correct"] for x in rs), "cited": sum(x["cited"] for x in rs),
                "keyword_ok": sum(x["keyword_ok"] for x in rs),
                "keyword_rate": round(sum(x["keyword_ok"] for x in rs) / n, 3) if n else 0.0,
                "correct_rate": round(sum(x["correct"] for x in rs) / n, 3) if n else 0.0,
                "citation_rate": round(sum(x["cited"] for x in rs) / n, 3) if n else 0.0}
    out = {"overall": r(records)}
    for s in sorted({x["surface"] for x in records}):
        out[s] = r([x for x in records if x["surface"] == s])
    return out


def write_markdown() -> None:
    """QUALITY.md from whichever runs exist, with per-question differences."""
    runs = {g: json.loads((OUT / f"quality_guard_{g}.json").read_text(encoding="utf-8"))
            for g in ("off", "on") if (OUT / f"quality_guard_{g}.json").exists()}
    lines = ["# Golden-set answer quality (reference RAG)", "",
             "Generated by `evals/run_quality.py`. Correct = all keywords present and at least one citation. "
             "Keywords only = all keywords present (citation ignored).", "",
             "| Slice | " + " | ".join(f"guard {g}: correct" for g in runs) + " | "
             + " | ".join(f"guard {g}: keywords only" for g in runs) + " | "
             + " | ".join(f"guard {g}: cited" for g in runs) + " |",
             "|---|" + "---|" * (3 * len(runs))]
    slices = sorted({k for r in runs.values() for k in r["rates"]}, key=lambda k: (k != "overall", k))
    for sl in slices:
        cells = [f"{r['rates'][sl]['correct']}/{r['rates'][sl]['n']} ({r['rates'][sl]['correct_rate']:.2f})"
                 for r in runs.values()]
        cells += [f"{r['rates'][sl]['keyword_ok']}/{r['rates'][sl]['n']} ({r['rates'][sl]['keyword_rate']:.2f})"
                  for r in runs.values()]
        cells += [f"{r['rates'][sl]['cited']}/{r['rates'][sl]['n']} ({r['rates'][sl]['citation_rate']:.2f})"
                  for r in runs.values()]
        lines.append(f"| {sl} | " + " | ".join(cells) + " |")
    if len(runs) == 2:
        off = {x["id"]: x for x in runs["off"]["records"]}
        diffs = [x for x in runs["on"]["records"] if x["correct"] != off[x["id"]]["correct"]
                 or x["cited"] != off[x["id"]]["cited"]]
        lines += ["", "## Per-question differences (guard off vs on)", ""]
        if not diffs:
            lines.append("None.")
        for x in diffs:
            o = off[x["id"]]
            lines.append(f"- `{x['id']}`: off correct={o['correct']} cited={o['cited']}; on correct={x['correct']} "
                         f"cited={x['cited']} refused={x['refused']}")
    lines.append("")
    (OUT / "QUALITY.md").write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--guard", choices=["on", "off"], required=True)
    ap.add_argument("--demo-url", default=os.environ.get("DEMO_URL", "http://localhost:8002"))
    args = ap.parse_args(argv)
    golden = yaml.safe_load(GOLDEN.read_text(encoding="utf-8"))["questions"]
    records = []
    with httpx.Client(base_url=args.demo_url, timeout=600) as http:
        for i, q in enumerate(golden, 1):
            r = http.post("/chat", json={"question": q["question"], "guard": args.guard})
            r.raise_for_status()
            body = r.json()
            j = judge(body["answer"], body["sources"], q["keywords"])
            records.append({"id": q["id"], "surface": q["surface"], "answer": body["answer"],
                            "sources": [s["doc_id"] for s in body["sources"]], "refused": body["refused"], **j})
            print(f"{i}/{len(golden)} {q['id']}: {'correct' if j['correct'] else 'wrong'}", flush=True)
    report = {"guard": args.guard, "rates": rates(records),
              "command": " ".join(["python", "evals/run_quality.py", *(argv or sys.argv[1:])]), "records": records}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"quality_guard_{args.guard}.json").write_text(json.dumps(report, indent=1, ensure_ascii=False),
                                                          encoding="utf-8")
    write_markdown()
    o = report["rates"]["overall"]
    print(f"quality guard {args.guard}: correct {o['correct']}/{o['n']}, cited {o['cited']}/{o['n']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
